// Enhanced apply function with smoother transitions
export const applyColorScheme = (schemeName) => {
  const scheme = colorSchemes[schemeName];
  if (!scheme) return;

  const root = document.documentElement;
  const colors = scheme.colors;

  // Add transition for smooth color changes
  root.style.transition = 'all 0.3s ease';

  // Apply all color variables with enhanced contrast
  root.style.setProperty('--background', colors.background);
  root.style.setProperty('--primary', colors.primary);
  root.style.setProperty('--primary-glow', colors.primaryGlow);
  root.style.setProperty('--secondary', colors.secondary);
  root.style.setProperty('--success', colors.success);
  root.style.setProperty('--destructive', colors.destructive);
  root.style.setProperty('--warning', colors.warning);
  root.style.setProperty('--bright', colors.bright);
  root.style.setProperty('--accent-bright', colors.accentBright);
  root.style.setProperty('--muted', colors.muted);
  root.style.setProperty('--border', colors.border);
  root.style.setProperty('--input', colors.input);
  root.style.setProperty('--ring', colors.ring);

  // Enhanced computed colors for better contrast and readability
  root.style.setProperty('--foreground', '0 0% 98%');
  root.style.setProperty('--card', `${colors.background}`);
  root.style.setProperty('--card-foreground', '0 0% 95%');
  root.style.setProperty('--popover', `${colors.muted}`);
  root.style.setProperty('--popover-foreground', '0 0% 95%');
  root.style.setProperty('--primary-foreground', '0 0% 5%');
  root.style.setProperty('--secondary-foreground', '0 0% 15%');
  root.style.setProperty('--muted-foreground', '0 0% 70%');
  root.style.setProperty('--accent', `${colors.primary}`);
  root.style.setProperty('--accent-foreground', '0 0% 5%');

  // Enhanced shadow effects inspired by the stress release game
  root.style.setProperty('--shadow-glow', `0 4px 20px hsl(${colors.primary} / 0.25), 0 0 40px hsl(${colors.primaryGlow} / 0.15)`);
  root.style.setProperty('--shadow-success-glow', `0 4px 20px hsl(${colors.success} / 0.3), 0 0 30px hsl(${colors.success} / 0.2)`);
  root.style.setProperty('--shadow-destructive-glow', `0 4px 20px hsl(${colors.destructive} / 0.3), 0 0 30px hsl(${colors.destructive} / 0.2)`);
  
  // Additional gradient variables for Stress Release Game style effects
  root.style.setProperty('--gradient-warm', `linear-gradient(135deg, hsl(${colors.primary}) 0%, hsl(${colors.secondary}) 100%)`);
  root.style.setProperty('--gradient-background', `linear-gradient(135deg, hsl(${colors.background}) 0%, hsl(${colors.muted}) 100%)`);
};

// Enhanced theme mapping with new themes
export const getColorSchemeFromTheme = (themeName) => {
  const themeMap = {
    'Football IQ': 'football',
    'Anime Quiz': 'anime', 
    'Science Quiz': 'science',
    'History Quiz': 'history',
    'Gaming Quiz': 'gaming',
    'General Knowledge': 'general',
    'Stress Relief': 'stressRelief',
    'Sunset Vibes': 'sunset',
    'Nature Quiz': 'nature',
    'Space Quiz': 'cosmic',
    'Ocean Quiz': 'ocean'
  };
  
  return themeMap[themeName] || 'stressRelief'; // Default to stress relief theme
};

// Enhanced initialization with smooth transitions
export const initializeTheme = (themeData) => {
  const colorScheme = getColorSchemeFromTheme(themeData?.name);
  
  // Add a small delay to ensure DOM is ready
  requestAnimationFrame(() => {
    applyColorScheme(colorScheme);
  });
};

// Utility function to get all available themes for selection
export const getAvailableThemes = () => {
  return Object.entries(colorSchemes).map(([key, scheme]) => ({
    key,
    name: scheme.name,
    preview: scheme.colors.primary
  }));
};